def test_upload_from_url_to_missing_parent_is_rejected(
    disk_client: YandexDiskClient,
    sandbox_path: str,
) -> None:
    """Negative: the destination's direct parent must exist."""
    missing_parent = unique_child(sandbox_path, "remote-missing-parent")
    file_path = f"{missing_parent}/result.txt"

    response = disk_client.upload_resource_from_url(
        file_path,
        REMOTE_FILE_URL,
        expected_statuses={409},
    )

    payload = assert_error_response(response, requests.codes.conflict)
    assert payload["error"] == "DiskPathDoesntExistsError"


def test_upload_from_url_with_invalid_token_returns_401(
    unauthorized_disk_client: YandexDiskClient,
    sandbox_path: str,
) -> None:
    """Negative: invalid OAuth credentials cannot start an import."""
    file_path = f"{unique_child(sandbox_path, 'unauthorized-remote-upload')}.txt"

    response = unauthorized_disk_client.upload_resource_from_url(
        file_path,
        REMOTE_FILE_URL,
        expected_statuses={401},
    )

    payload = assert_error_response(response, requests.codes.unauthorized)
    assert payload["error"] == "UnauthorizedError"
